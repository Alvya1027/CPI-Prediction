function twin_model_file = build_twin_shared_reservoir_model(config, rebuild)
%BUILD_TWIN_SHARED_RESERVOIR_MODEL Build two explicit shared Model branches.
%
% Both Model blocks reference the exact same SL_RC_shared_branch model file.
% They have independent dynamic states but cannot have different structures
% or physical parameters.

if nargin < 1 || isempty(config)
    config = config_twin_cpi_rc();
end
if nargin < 2
    rebuild = false;
end
build_shared_reservoir_branch_model(config, rebuild);
twin_model_file = config.twin_model_file;
if isfile(twin_model_file) && ~rebuild
    return;
end
[~, branch_name] = fileparts(config.branch_model_file);
[~, twin_name] = fileparts(twin_model_file);
if bdIsLoaded(twin_name)
    close_system(twin_name, 0);
end
if isfile(twin_model_file)
    delete(twin_model_file);
end
new_system(twin_name);
open_system(twin_name);

target_source = add_block('simulink/Sources/From Workspace', ...
    [twin_name '/Target Window Sequence'], ...
    'VariableName', config.target_input_variable, ...
    'Interpolate', 'off', ...
    'Position', [40, 75, 150, 105]);
reference_source = add_block('simulink/Sources/From Workspace', ...
    [twin_name '/Reference Window Sequence'], ...
    'VariableName', config.reference_input_variable, ...
    'Interpolate', 'off', ...
    'Position', [40, 245, 150, 275]);

target_branch = add_block('simulink/Ports & Subsystems/Model', ...
    [twin_name '/Target Shared Optical Reservoir'], ...
    'ModelName', branch_name, 'SimulationMode', 'Normal', ...
    'Position', [245, 55, 455, 125]);
reference_branch = add_block('simulink/Ports & Subsystems/Model', ...
    [twin_name '/Reference Shared Optical Reservoir'], ...
    'ModelName', branch_name, 'SimulationMode', 'Normal', ...
    'Position', [245, 225, 455, 295]);

target_logger = add_block('simulink/Sinks/To Workspace', ...
    [twin_name '/Target State Logger'], ...
    'VariableName', config.target_output_variable, ...
    'SaveFormat', 'Timeseries', ...
    'SampleTime', num2str(config.logger_sample_time_seconds, '%.17g'), ...
    'Position', [555, 75, 675, 105]);
reference_logger = add_block('simulink/Sinks/To Workspace', ...
    [twin_name '/Reference State Logger'], ...
    'VariableName', config.reference_output_variable, ...
    'SaveFormat', 'Timeseries', ...
    'SampleTime', num2str(config.logger_sample_time_seconds, '%.17g'), ...
    'Position', [555, 245, 675, 275]);

add_line(twin_name, get_param(target_source, 'PortHandles').Outport(1), ...
    get_param(target_branch, 'PortHandles').Inport(1), 'autorouting', 'on');
add_line(twin_name, get_param(reference_source, 'PortHandles').Outport(1), ...
    get_param(reference_branch, 'PortHandles').Inport(1), 'autorouting', 'on');
add_line(twin_name, get_param(target_branch, 'PortHandles').Outport(1), ...
    get_param(target_logger, 'PortHandles').Inport(1), 'autorouting', 'on');
add_line(twin_name, get_param(reference_branch, 'PortHandles').Outport(1), ...
    get_param(reference_logger, 'PortHandles').Inport(1), 'autorouting', 'on');

set_param(twin_name, 'SolverType', 'Fixed-step', 'Solver', config.solver, ...
    'FixedStep', num2str(config.fixed_step_seconds, '%.17g'), ...
    'StartTime', '0', ...
    'StopTime', '4.1e-6', 'LoadInitialState', 'off', ...
    'SaveFinalState', 'off', 'FastRestart', 'off');
save_system(twin_name, twin_model_file);
close_system(twin_name, 0);

% Confirm the file really contains two instances of one shared model.
load_system(twin_model_file);
model_blocks = find_system(twin_name, 'SearchDepth', 1, ...
    'BlockType', 'ModelReference');
assert(numel(model_blocks) == 2, ...
    'Twin model must contain exactly two Model Reference branches.');
assert(all(strcmp(get_param(model_blocks, 'ModelName'), branch_name)), ...
    'Both twin branches must reference the same branch model.');
save_system(twin_name, twin_model_file);
close_system(twin_name, 0);
fprintf('Built explicit twin reservoir model: %s\n', twin_model_file);
end
