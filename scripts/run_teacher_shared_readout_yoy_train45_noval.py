"""Run the fixed-config YoY shared-readout Siamese experiment.

This experiment consumes the continuous-window optical states generated by
MATLAB for the 45-target training split and the 47-target test split.  The
reservoir and mask stay frozen; only one output readout shared by both
semantic branches is fitted.  Test references come exclusively from train45
and are ranked by input-window distance without using test labels.
"""

