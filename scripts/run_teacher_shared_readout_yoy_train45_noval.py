import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.io import loadmat

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import RESULTS_DIR, ROOT_DIR
from src.siamese_split_isolation import load_isolated_split
from src.teacher_shared_readout import fit_joint_shared_readout
from src.teacher_shared_readout_pipeline import (
    FrozenTeacherConfig,
    _metrics,
    _state_matrix,
    build_evaluation_candidates,
    build_train_pairs,
    predict_direct_split,
    predict_reference_split,
    select_references,
)


PROFILE_ROOT = (
    ROOT_DIR / "matlab" / "optical_reservoir_cpi_yoy_train45_noval_20260807"
)
DATA_DIR = PROFILE_ROOT / "data"
STATE_DIR = PROFILE_ROOT / "states"
SINGLE_RESULT_DIR = RESULTS_DIR / "optical_reservoir_yoy_train45_noval_20260807"
OUTPUT_DIR = (
    RESULTS_DIR / "siamese_optical_yoy_teacher_shared_readout_train45_noval_20260807"
)

# These values were fixed before this YoY test run by the completed MoM
# train45/test47 protocol.  They must not be changed after viewing this output.
FIXED_CONFIG = FrozenTeacherConfig(
    alpha=100.0,
    pair_weight=0.1,
    k_references=5,
    aggregation="mean",
    min_gap_months=1,
    absolute_alpha=100.0 / 45.0,
)

EXPECTED_SPLITS = {
    "train": (45, "2018-09", "2022-05"),
    "test": (47, "2022-06", "2026-04"),
}
STATE_PROTOCOL = "continuous_serial_shared_fixed_reservoir"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_json(path: Path, payload: object) -> None:
    serialized = json.dumps(payload, ensure_ascii=False, indent=2) + "\n"
    path.write_bytes(serialized.encode("utf-8"))


def _load_split(split: str) -> dict[str, object]:
    payload = load_isolated_split(DATA_DIR, split)
    expected_count, first_date, last_date = EXPECTED_SPLITS[split]
    index = payload["index"]
    if len(index) != expected_count:
        raise ValueError(f"{split} has {len(index)} rows; expected {expected_count}")
    if (
        str(index["target_date"].iloc[0]) != first_date
        or str(index["target_date"].iloc[-1]) != last_date
    ):
        raise ValueError(f"{split} target dates do not match the fixed boundary")
    return payload


def _load_states(
    split_payloads: dict[str, dict[str, object]],
) -> tuple[dict[int, np.ndarray], dict[str, object]]:
    lookup: dict[int, np.ndarray] = {}
    masks: list[np.ndarray] = []
    split_audit: dict[str, object] = {}
    width: int | None = None
    for split, data in split_payloads.items():
        state_path = STATE_DIR / f"states_{split}.mat"
        raw = loadmat(state_path)
        required = {"state_matrix", "sample_id", "target", "mask"}
        missing = required.difference(raw)
        if missing:
            raise ValueError(f"{state_path} lacks fields: {sorted(missing)}")
        states = np.asarray(raw["state_matrix"], dtype=np.float64)
        sample_ids = np.asarray(raw["sample_id"]).reshape(-1).astype(int)
        targets = np.asarray(raw["target"], dtype=np.float64).reshape(-1)
        index = data["index"].reset_index(drop=True)
        expected_ids = index["sample_id"].to_numpy(dtype=int)
        expected_targets = np.asarray(data["y"], dtype=np.float64).reshape(-1)
        if states.shape != (len(index), 50):
            raise ValueError(f"invalid {split} state shape: {states.shape}")
        if not np.array_equal(sample_ids, expected_ids):
            raise ValueError(f"{split} state IDs disagree with the isolated data")
        if not np.allclose(targets, expected_targets):
            raise ValueError(f"{split} targets disagree with the isolated data")
        if not np.isfinite(states).all() or float(np.std(states)) == 0.0:
            raise ValueError(f"{split} states are non-finite or constant")
        width = states.shape[1] if width is None else width
        if states.shape[1] != width:
            raise ValueError("train and test states use different widths")
        for sample_id, state in zip(sample_ids, states):
            if int(sample_id) in lookup:
                raise ValueError(f"duplicate state ID: {sample_id}")
            lookup[int(sample_id)] = state
        masks.append(np.asarray(raw["mask"]))
        split_audit[split] = {
            "state_file": str(state_path.relative_to(ROOT_DIR)),
            "sha256": _sha256(state_path),
            "shape": [int(value) for value in states.shape],
            "first_target_date": str(index["target_date"].iloc[0]),
            "last_target_date": str(index["target_date"].iloc[-1]),
        }
    if not all(np.array_equal(masks[0], mask) for mask in masks[1:]):
        raise ValueError("train and test states do not share the same fixed mask")
    return lookup, {
        "status": "passed",
        "state_protocol": STATE_PROTOCOL,
        "state_width": int(width or 0),
        "shared_fixed_mask": True,
        "loaded_splits": list(split_payloads),
        "splits": split_audit,
    }


def _load_official_single_test() -> tuple[pd.DataFrame, dict[str, float]]:
    predictions = pd.read_csv(
        SINGLE_RESULT_DIR / "tables" / "optical_reservoir_predictions.csv"
    )
    test = predictions.loc[predictions["split"].eq("test")].copy()
    if len(test) != 47:
        raise ValueError("official single-reservoir result does not contain test47")
    metrics = pd.read_csv(
        SINGLE_RESULT_DIR / "tables" / "optical_reservoir_metrics.csv"
    )
    row = metrics.loc[metrics["split"].eq("test")].iloc[0]
    return test, {"mae": float(row["mae"]), "rmse": float(row["rmse"])}


def _save_figures(
    unified: pd.DataFrame, comparison: pd.DataFrame, figure_dir: Path
) -> None:
    figure_dir.mkdir(parents=True, exist_ok=True)
    fig, axis = plt.subplots(figsize=(11.5, 5.0))
    axis.plot(
        unified["target_date"],
        unified["cpi_actual"],
        color="black",
        linewidth=2,
        label="Actual YoY CPI",
    )
    axis.plot(
        unified["target_date"],
        unified["cpi_predicted_single"],
        label="Single optical reservoir",
    )
    axis.plot(
        unified["target_date"],
        unified["cpi_predicted_siamese"],
        label="Shared-readout Siamese",
    )
    axis.set_xlabel("Test target month")
    axis.set_ylabel("CPI YoY index (previous-year same month = 100)")
    axis.set_title("YoY CPI: single vs shared-readout Siamese (train45/test47)")
    axis.tick_params(axis="x", rotation=60)
    axis.grid(alpha=0.25)
    axis.legend()
    fig.tight_layout()
    fig.savefig(figure_dir / "yoy_test_prediction_comparison.png", dpi=180)
    plt.close(fig)

    fig, axis = plt.subplots(figsize=(8.5, 4.8))
    x = np.arange(len(comparison))
    width = 0.36
    axis.bar(x - width / 2, comparison["test_mae"], width, label="MAE")
    axis.bar(x + width / 2, comparison["test_rmse"], width, label="RMSE")
    axis.set_xticks(x, comparison["display_name"], rotation=12, ha="right")
    axis.set_ylabel("Test error")
    axis.set_title("YoY CPI test metrics")
    axis.grid(axis="y", alpha=0.25)
    axis.legend()
    fig.tight_layout()
    fig.savefig(figure_dir / "yoy_test_metric_comparison.png", dpi=180)
    plt.close(fig)


def main() -> None:
    train = _load_split("train")
    test = _load_split("test")
    state_lookup, state_audit = _load_states({"train": train, "test": test})

    train_ids = train["index"]["sample_id"].to_numpy(dtype=int)
    train_states = _state_matrix(train_ids, state_lookup)
    train_targets = np.asarray(train["y"], dtype=np.float64).reshape(-1)
    train_pairs, pair_i, pair_j = build_train_pairs(
        train, min_gap_months=FIXED_CONFIG.min_gap_months
    )
    if len(train_pairs) != 561:
        raise ValueError(f"train45 gap=1 must produce 561 pairs; got {len(train_pairs)}")

    model = fit_joint_shared_readout(
        train_states,
        train_targets,
        pair_i,
        pair_j,
        alpha=FIXED_CONFIG.alpha,
        pair_weight=FIXED_CONFIG.pair_weight,
        absolute_weight=1.0,
    )
    direct_predictions = predict_direct_split(model, test, state_lookup)
    candidates = build_evaluation_candidates(
        test, train, min_gap_months=FIXED_CONFIG.min_gap_months
    )
    selected = select_references(candidates, FIXED_CONFIG.k_references)
    pair_predictions, siamese_predictions = predict_reference_split(
        model, selected, state_lookup, FIXED_CONFIG.aggregation
    )
    if len(siamese_predictions) != 47:
        raise ValueError("Siamese output does not contain exactly 47 test targets")

    single_predictions, single_metrics = _load_official_single_test()
    direct_metrics = _metrics(direct_predictions)
    siamese_metrics = _metrics(siamese_predictions)
    comparison = pd.DataFrame(
        [
            {
                "model": "single_optical_reservoir",
                "display_name": "Single optical reservoir",
                "test_mae": single_metrics["mae"],
                "test_rmse": single_metrics["rmse"],
            },
            {
                "model": "joint_shared_readout_direct_diagnostic",
                "display_name": "Joint readout (direct)",
                "test_mae": direct_metrics["mae"],
                "test_rmse": direct_metrics["rmse"],
            },
            {
                "model": "siamese_shared_readout_pair",
                "display_name": "Shared-readout Siamese",
                "test_mae": siamese_metrics["mae"],
                "test_rmse": siamese_metrics["rmse"],
            },
        ]
    )
    comparison["mae_change_vs_single_pct"] = (
        comparison["test_mae"] / single_metrics["mae"] - 1.0
    ) * 100.0
    comparison["rmse_change_vs_single_pct"] = (
        comparison["test_rmse"] / single_metrics["rmse"] - 1.0
    ) * 100.0

    unified = single_predictions[
        ["sample_id", "target_date", "cpi_actual", "cpi_predicted"]
    ].rename(
        columns={
            "sample_id": "sample_i_id",
            "cpi_predicted": "cpi_predicted_single",
        }
    )
    unified = unified.merge(
        direct_predictions[
            ["sample_i_id", "target_date", "cpi_actual", "cpi_predicted"]
        ].rename(columns={"cpi_predicted": "cpi_predicted_joint_direct"}),
        on=["sample_i_id", "target_date", "cpi_actual"],
        validate="one_to_one",
    ).merge(
        siamese_predictions[
            ["sample_i_id", "target_date", "cpi_actual", "cpi_predicted"]
        ].rename(columns={"cpi_predicted": "cpi_predicted_siamese"}),
        on=["sample_i_id", "target_date", "cpi_actual"],
        validate="one_to_one",
    )
    for suffix in ("single", "joint_direct", "siamese"):
        unified[f"residual_{suffix}"] = (
            unified[f"cpi_predicted_{suffix}"] - unified["cpi_actual"]
        )
        unified[f"absolute_error_{suffix}"] = unified[f"residual_{suffix}"].abs()

    table_dir = OUTPUT_DIR / "tables"
    model_dir = OUTPUT_DIR / "models"
    figure_dir = OUTPUT_DIR / "figures"
    for directory in (table_dir, model_dir, figure_dir):
        directory.mkdir(parents=True, exist_ok=True)
    comparison.to_csv(table_dir / "test_model_comparison.csv", index=False)
    unified.to_csv(table_dir / "test_prediction_comparison.csv", index=False)
    train_pairs.to_csv(table_dir / "train_pair_relations.csv", index=False)
    selected.to_csv(table_dir / "selected_test_references.csv", index=False)
    pair_predictions.to_csv(
        table_dir / "selected_test_pair_predictions.csv", index=False
    )
    np.savez_compressed(
        model_dir / "teacher_shared_readout_yoy_train45.npz", **model.to_npz_dict()
    )
    _save_figures(unified, comparison, figure_dir)

    manifest = {
        "experiment": "YoY shared-readout Siamese train45/test47 no validation",
        "created_at": datetime.now().astimezone().isoformat(),
        "source": "data_processed/cpi_data_lastyear=100.csv actual sequence",
        "target_scale": "CPI YoY index (previous-year same month=100)",
        "window_protocol": "continuous previous 12 actual YoY values; one-step ahead",
        "split_protocol": "train 2018-09..2022-05 (45), test 2022-06..2026-04 (47), no validation",
        "state_protocol": STATE_PROTOCOL,
        "architecture_scope": (
            "semantic target/reference branches resolved from one fixed-reservoir "
            "unique-window state cache; not simultaneous explicit-Twin MATLAB simulation"
        ),
        "configuration": asdict(FIXED_CONFIG),
        "configuration_policy": (
            "copied from the predeclared MoM train45/test47 protocol before this YoY run; "
            "no YoY test metric used for selection"
        ),
        "training_targets": 45,
        "derived_training_pairs": int(len(train_pairs)),
        "test_targets": 47,
        "test_references_per_target": FIXED_CONFIG.k_references,
        "all_test_references_from_train45": True,
        "test_labels_used_for_reference_selection": False,
        "reservoir_parameters_trained": False,
        "only_shared_output_weights_trained": True,
        "state_audit": state_audit,
        "data_manifest_sha256": _sha256(DATA_DIR / "isolated_split_manifest.json"),
        "test_metrics": {
            "single_optical_reservoir": single_metrics,
            "joint_shared_readout_direct_diagnostic": direct_metrics,
            "siamese_shared_readout_pair": siamese_metrics,
        },
    }
    _write_json(OUTPUT_DIR / "experiment_manifest.json", manifest)

    readme = f"""# 同比孪生光储备池 train45/test47 结果\n\n数据使用 `cpi_data_lastyear=100.csv` 的 `actual` 同比序列，以连续前12个月预测下1个月。训练目标为2018-09至2022-05（45个），无验证集；测试目标为2022-06至2026-04（47个）。\n\n本次使用 MATLAB 新上传的单路连续窗口状态缓存，并在 Python 中构造目标/参考语义分支、共享一个线性输出权重，预测目标与参考的CPI差值。该结果不是两个分支在 MATLAB 中同时仿真的严格显式 Twin 结果。\n\n- 单光储备池：MAE={single_metrics['mae']:.6f}，RMSE={single_metrics['rmse']:.6f}\n- 孪生共享读出：MAE={siamese_metrics['mae']:.6f}，RMSE={siamese_metrics['rmse']:.6f}\n- 相对单光储备池：MAE变化={(siamese_metrics['mae']/single_metrics['mae']-1)*100:.2f}%，RMSE变化={(siamese_metrics['rmse']/single_metrics['rmse']-1)*100:.2f}%（正数表示误差增大）\n\n配置在读取本次同比测试指标前固定为：gap=1、K=5、均值聚合、alpha=100、pair_weight=0.1。测试参考只来自train45，选择过程不使用测试标签。\n"""
    (OUTPUT_DIR / "README.md").write_bytes(readme.encode("utf-8"))
    print(comparison.to_string(index=False))
    print(f"Output: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
